def _status_of(exc: Exception) -> int:
    for attr in ("code", "status_code"):
        val = getattr(exc, attr, None)
        if isinstance(val, int):
            return val
    text = str(exc)
    for code in (429, 503, 500, 404, 400, 401, 403):
        if re.search(rf"\b{code}\b", text):
            return code
    return 0


def friendly_ai_error(exc: Exception) -> tuple[int, str]:
    code = _status_of(exc)
    if code == 429:
        return 429, "تم تجاوز حد الاستخدام المجاني لـ Gemini مؤقتاً؛ انتظر دقيقة ثم حاول مرة أخرى."
    if code in (500, 503):
        return 503, "خدمة Gemini مزدحمة أو غير متاحة حالياً؛ حاول مرة أخرى بعد قليل."
    if code == 404:
        return 502, "اسم نموذج Gemini غير صحيح أو غير متاح لحسابك؛ اضبط GEMINI_MODEL في ملف .env."
    if code in (401, 403):
        return 502, "مفتاح GEMINI_API_KEY غير صالح أو لا يملك صلاحية؛ تحقق منه في ملف .env."
    return 502, f"تعذر الاتصال بخدمة Gemini: {str(exc)[:200]}"


async def gemini_generate(contents, config=None, retries: int = 1):
    models = list(dict.fromkeys([MODEL_ID] + FALLBACK_MODELS))
    last_exc: Optional[Exception] = None
    request_timeout = 50

    for model_name in models:
        for attempt in range(retries + 1):
            try:
                kwargs = {"model": model_name, "contents": contents}
                if config is not None:
                    kwargs["config"] = config

                return await asyncio.wait_for(
                    client.aio.models.generate_content(**kwargs),
                    timeout=request_timeout
                )

            except asyncio.TimeoutError as exc:
                last_exc = exc
                print(
                    f"[GEMINI TIMEOUT] model={model_name} "
                    f"after {request_timeout} seconds"
                )
                break

            except Exception as exc:
                last_exc = exc
                print(
                    f"[GEMINI ERROR] model={model_name} "
                    f"attempt={attempt+1}: {exc}"
                )

                code = _status_of(exc)

                if code in (400, 401, 403):
                    raise

                if code == 404:
                    break

                if code in (429, 500, 503):
                    if attempt < retries:
                        await asyncio.sleep(1)
                        continue
                    break

                raise

    if isinstance(last_exc, asyncio.TimeoutError):
        raise HTTPException(
            status_code=504,
            detail="\u062a\u0623\u062e\u0631 \u0631\u062f Gemini. \u062d\u0627\u0648\u0644\u064a \u0645\u0631\u0629 \u0623\u062e\u0631\u0649."
        )
    raise last_exc if last_exc else RuntimeError("??? ??????? Gemini.")


def extract_json_clean(raw: str) -> dict:
    cleaned = raw.strip()
    cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned, flags=re.IGNORECASE)
    cleaned = re.sub(r"\s*```$", "", cleaned)
    start = cleaned.find("{")
    end = cleaned.rfind("}")
    if start != -1 and end != -1 and end > start:
        cleaned = cleaned[start : end + 1]
    return json.loads(cleaned)


EDGE_TTS_VOICES = {
    "female": "ar-EG-SalmaNeural",
    "male": "ar-EG-ShakirNeural",
}


async def synthesize_arabic_mp3_base64(
    text: str, voice: str = "female", allow_fallback: bool = True
) -> tuple[str, str]:
    clean = re.sub(r"[#*`_~•\-]+", " ", str(text or "")).strip()
    if not clean:
        return "", "unavailable"

    voice_key = voice if voice in EDGE_TTS_VOICES else "female"
    clean = clean[:3500]

    if HAS_EDGE_TTS:
        try:
            async def generate_edge_audio():
                communicator = edge_tts.Communicate(
                    text=clean,
                    voice=EDGE_TTS_VOICES[voice_key],
                    rate="-5%",
                    pitch="-1Hz",
                )
                audio = bytearray()
                async for chunk in communicator.stream():
                    if chunk.get("type") == "audio":
                        audio.extend(chunk.get("data", b""))
                return bytes(audio)

            audio = await asyncio.wait_for(generate_edge_audio(), timeout=50)
            if audio:
                return base64.b64encode(audio).decode("utf-8"), "edge-tts"
            raise RuntimeError("Empty Edge TTS audio")

        except Exception as exc:
            print(f"[EDGE TTS ERROR] voice={voice_key} chars={len(clean)} type={type(exc).__name__}: {exc}", flush=True)

    # Preserve the old audio service as a fallback.
    if allow_fallback and HAS_GTTS and gTTS is not None:
        try:
            def generate_gtts_audio():
                tts = gTTS(text=clean, lang="ar", slow=False)
                fp = io.BytesIO()
                tts.write_to_fp(fp)
                return fp.getvalue()

            audio = await asyncio.wait_for(
                asyncio.to_thread(generate_gtts_audio), timeout=25
            )
            if audio:
                return base64.b64encode(audio).decode("utf-8"), "gtts-fallback"

        except Exception as exc:
            print(f"[GTTS FALLBACK ERROR] {type(exc).__name__}: {exc}", flush=True)

    return "", "unavailable"


async def collect_multimodal_inputs(
    text_content: str, files: Optional[List[UploadFile]]
) -> tuple[str, list]:
    combined_texts = []
    if text_content and text_content.strip():
        combined_texts.append(text_content.strip())

    media_parts = []
    if files:
        for f in files:
            if not f or not f.filename:
                continue
            raw_bytes = await f.read()
            if not raw_bytes:
                continue

            fname = f.filename.lower()
            ctype = (f.content_type or "").lower()

            if fname.endswith(".txt") or "text/plain" in ctype:
                try:
                    decoded = raw_bytes.decode("utf-8", errors="ignore").strip()
                    if decoded:
                        combined_texts.append(f"--- محتوى ملف {f.filename} ---\n{decoded}")
                except Exception:
                    pass

            elif fname.endswith(".pdf") or "application/pdf" in ctype:
                extracted_pages = []
                try:
                    reader = PdfReader(io.BytesIO(raw_bytes))
                    for idx, page in enumerate(reader.pages):
                        p_txt = (page.extract_text() or "").strip()
                        if p_txt:
                            extracted_pages.append(f"[صفحة {idx + 1}]\n{p_txt}")
                except Exception:
                    extracted_pages = []

                full_pdf_text = "\n\n".join(extracted_pages).strip()
                if len(full_pdf_text) >= 100:
                    combined_texts.append(f"--- محتوى PDF ({f.filename}) ---\n{full_pdf_text}")
                else:
                    media_parts.append(
                        types.Part.from_bytes(data=raw_bytes, mime_type="application/pdf")
                    )

            elif any(fname.endswith(ext) for ext in (".jpg", ".jpeg", ".png", ".webp")) or ctype.startswith("image/"):
                mime = ctype if ctype.startswith("image/") else "image/jpeg"
                media_parts.append(types.Part.from_bytes(data=raw_bytes, mime_type=mime))

    return "\n\n".join(combined_texts).strip(), media_parts


def chunk_large_text(text: str, max_chars: int = 28000) -> List[str]:
    if len(text) <= max_chars:
        return [text]
    chunks = []
    start = 0
    while start < len(text):
        end = min(len(text), start + max_chars)
        if end < len(text):
            nl = text.rfind("\n", start, end)
            if nl > start + int(max_chars * 0.6):
                end = nl
        chunks.append(text[start:end].strip())
        start = end
    return [c for c in chunks if c]


